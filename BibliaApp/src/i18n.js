export function translate(language, key, params) {
  const dict = STRINGS[language] || STRINGS['pt-BR'];
  let text = dict[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.split(`{${k}}`).join(String(v));
    });
  }
  return text;
}