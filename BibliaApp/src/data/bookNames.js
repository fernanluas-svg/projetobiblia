// Nome de exibição no idioma da interface ('pt-BR' | 'en' | 'es').
// A identidade do livro continua sendo abbrev (bookList); isto é só rótulo.
export function getBookName(abbrev, language) {
  if (language === 'en') return EN[abbrev] ?? abbrev;
  if (language === 'es') return ES[abbrev] ?? abbrev;
  return bookList.find((b) => b.abbrev === abbrev)?.name ?? abbrev;
}
